"""Python 3.13's str.casefold() as a Rust table for kiwi-server's modpacks
(variant entries sort by title casefold), from the repo root:
    S:/Desktop/Projects/.venvs/trove-prod/Scripts/python.exe native/port/parity/gen_modpacks_casefold.py
Writes native/kiwi-server/src/modpacks/casefold_table.rs: runs of code points
whose single-character fold is a constant offset (stride 1 or 2), plus the
multi-character folds.
"""
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "native" / "kiwi-server" / "src" / "modpacks" / "casefold_table.rs"

singles, multi = [], []
for cp in range(0x110000):
    if 0xD800 <= cp < 0xE000:
        continue
    f = chr(cp).casefold()
    if f == chr(cp):
        continue
    if len(f) == 1:
        singles.append((cp, ord(f) - cp))
    else:
        multi.append((cp, f))

runs = []
for cp, delta in singles:
    if runs:
        start, end, stride, d = runs[-1]
        if d == delta:
            step = cp - end
            if (start == end and step in (1, 2)) or step == stride:
                runs[-1] = (start, cp, step, d)
                continue
    runs.append((cp, cp, 1, delta))

BS = chr(92)


def esc(s: str) -> str:
    return "".join(f"{BS}u{{{ord(c):x}}}" for c in s)


lines = [
    f"// Generated by native/port/parity/gen_modpacks_casefold.py (Unicode {unicodedata.unidata_version}).",
    "",
    "/// `(first, last, stride, delta)`: every `stride`-th code point of the run folds to itself plus `delta`.",
    "pub const RUNS: &[(u32, u32, u32, i32)] = &[",
]
lines += [f"    (0x{a:x}, 0x{b:x}, {s}, {d})," for a, b, s, d in runs]
lines += ["];", "", "pub const MULTI: &[(u32, &str)] = &["]
lines += [f'    (0x{cp:x}, "{esc(f)}"),' for cp, f in multi]
lines += ["];", ""]
OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
print(len(runs), "runs,", len(multi), "multi")
