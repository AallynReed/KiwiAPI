MAX = 0x110000


def runs(fn):
    out, prev = [], object()
    for cp in range(MAX):
        v = fn(cp)
        if v != prev:
            out.append((cp, v))
            prev = v
    return out


def ranges(pred):
    out, start = [], None
    for cp in range(MAX + 1):
        hit = cp < MAX and pred(cp)
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


def rs(s: str) -> str:
    out = []
    for c in s:
        o = ord(c)
        if c == '"' or c == "\\":
            out.append("\\" + c)
        elif 0x20 <= o < 0x7F:
            out.append(c)
        else:
            out.append(f"\\u{{{o:x}}}")
    return '"' + "".join(out) + '"'


def emit(lines, name, ty, items, per=8):
    lines.append(f"pub const {name}: {ty} = &[")
    for i in range(0, len(items), per):
        lines.append("    " + ", ".join(items[i:i + per]) + ",")
    lines.append("];")


def intranges(t):
    return [((r >> 32), (r & 0xFFFFFFFF) - 1) for r in t]


def tables() -> None:
    cats = sorted({unicodedata.category(chr(c)) for c in range(MAX)})
    bidis = sorted({unicodedata.bidirectional(chr(c)) for c in range(MAX)})
    lines = [
        "//! Unicode 15.1.0 (Python 3.13 `unicodedata`) and idna 3.20 (UTS #46 "
        + idnadata.__version__ + ") data for the email validator.",
        "//! Generated by native/port/parity/gen_email_validator.py tables; do not edit.",
        "",
        f"pub const CATEGORIES: [&str; {len(cats)}] = [{', '.join(rs(c) for c in cats)}];",
    ]
    emit(lines, "CATEGORY", "&[(u32, u8)]",
         [f"(0x{s:x}, {cats.index(v)})" for s, v in runs(lambda c: unicodedata.category(chr(c)))])
    lines.append(f"pub const BIDIS: [&str; {len(bidis)}] = [{', '.join(rs(b) for b in bidis)}];")
    emit(lines, "BIDI", "&[(u32, u8)]",
         [f"(0x{s:x}, {bidis.index(v)})" for s, v in runs(lambda c: unicodedata.bidirectional(chr(c)))])
    emit(lines, "CCC", "&[(u32, u8)]",
         [f"(0x{s:x}, {v})" for s, v in runs(lambda c: unicodedata.combining(chr(c)))])
    decomp, compose = [], []
    for cp in range(MAX):
        d = unicodedata.decomposition(chr(cp))
        if not d or d.startswith("<") or 0xAC00 <= cp <= 0xD7A3:
            continue
        parts = [int(p, 16) for p in d.split()]
        decomp.append(f"(0x{cp:x}, 0x{parts[0]:x}, 0x{parts[1] if len(parts) > 1 else 0:x})")
        if len(parts) == 2 and unicodedata.normalize("NFC", chr(cp)) == chr(cp):
            compose.append((parts[0], parts[1], cp))
    emit(lines, "DECOMP", "&[(u32, u32, u32)]", decomp, 6)
    emit(lines, "COMPOSE", "&[(u32, u32, u32)]", [f"(0x{a:x}, 0x{b:x}, 0x{c:x})" for a, b, c in sorted(compose)], 6)
    emit(lines, "DOT_DECOMP", "&[u32]",
         [f"0x{c:x}" for c in range(MAX) if "002E" in unicodedata.decomposition(chr(c)).split(" ")], 12)
    names = [
        f"(0x{c:x}, {rs(unicodedata.name(chr(c)))})" for c in range(MAX)
        if unicodedata.category(chr(c))[0] in "MZC" and unicodedata.name(chr(c), None)
    ]
    emit(lines, "NAMES", "&[(u32, &str)]", names, 3)
    emit(lines, "NAMELESS", "&[(u32, u32)]",
         [f"(0x{a:x}, 0x{b:x})" for a, b in ranges(lambda c: unicodedata.name(chr(c), None) is None)])
    emit(lines, "WORD", "&[(u32, u32)]",
         [f"(0x{a:x}, 0x{b:x})" for a, b in ranges(lambda c: chr(c).isalnum() or c == 0x5F)])
    emit(lines, "UTS46_STARTS", "&[u32]", [f"0x{s:x}" for s in uts46_starts], 12)
    lines.append("pub const UTS46_STATUS: &[u8] = b\"" + bytes(uts46_statuses).decode("ascii") + "\";")
    emit(lines, "UTS46_REPL", "&[&str]", [rs(r or "") for r in uts46_replacements], 12)
    for key in ("PVALID", "CONTEXTJ", "CONTEXTO"):
        emit(lines, key, "&[(u32, u32)]", [f"(0x{a:x}, 0x{b:x})" for a, b in intranges(idnadata.codepoint_classes[key])])
    for key in ("Greek", "Han", "Hebrew", "Hiragana", "Katakana"):
        emit(lines, "SCRIPT_" + key.upper(), "&[(u32, u32)]",
             [f"(0x{a:x}, 0x{b:x})" for a, b in intranges(idnadata.scripts[key])])
    jt = sorted((a, b, k) for k, v in idnadata.joining_types.items() for a, b in intranges(v))
    emit(lines, "JOINING", "&[(u32, u32, u8)]", [f"(0x{a:x}, 0x{b:x}, b'{k}')" for a, b, k in jt], 6)
    TABLE.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(TABLE, TABLE.stat().st_size)


def outcome(fn, value):
    try:
        return {"ok": fn(value)}
    except ValidationError as e:
        err = e.errors()[0]
        return {"err": err["msg"]}
    except email_validator.EmailNotValidError as e:
        return {"err": str(e)}


