def fixtures() -> None:
    adapter = TypeAdapter(EmailStr)
    direct = lambda v: email_validator.validate_email(v, check_deliverability=False).normalized  # noqa: E731
    cases = [{"in": s, "pydantic": outcome(adapter.validate_python, s), "direct": outcome(direct, s)} for s in corpus()]
    nfc = [[c, unicodedata.normalize("NFC", chr(c))] for c in range(MAX)
           if not 0xD800 <= c < 0xE000 and unicodedata.normalize("NFC", chr(c)) != chr(c)]
    rnd = random.Random(7)
    marks = [c for c in range(0x300, 0x370)] + [0x1100, 0x1161, 0x11a8, 0xac00, 0x0f71, 0x0f72, 0x0f74, 0x0915, 0x093c]
    strings = []
    for _ in range(500):
        s = "".join(chr(rnd.choice(marks + [0x41, 0x61, 0x45, 0x3b1, 0x1e9b, 0x323])) for _ in range(rnd.randint(1, 8)))
        strings.append([s, unicodedata.normalize("NFC", s)])
    GOLDEN.parent.mkdir(parents=True, exist_ok=True)
    GOLDEN.write_text(json.dumps({"cases": cases, "nfc_chars": nfc, "nfc_strings": strings}, ensure_ascii=True,
                                 indent=0) + "\n", encoding="utf-8", newline="\n")
    print(GOLDEN, len(cases), "cases", idna.__version__)


