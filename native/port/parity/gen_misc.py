def ranges(pred):
    out, start = [], None
    for c in range(0x80, 0x110000):
        hit = pred(chr(c))
        if hit and start is None:
            start = c
        if not hit and start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def rust_table(name, rs):
    lines, line = [f"pub const {name}: &[(u32, u32)] = &["], "   "
    for a, b in rs:
        item = f" (0x{a:x}, 0x{b:x}),"
        if len(line) + len(item) > 116:
            lines.append(line)
            line = "   "
        line += item
    return lines + [line, "];"]


def tables() -> None:
    out = [
        f"//! Python `str` predicates above U+007F (Unicode {unicodedata.unidata_version}).",
        "//! Generated by native/port/parity/gen_misc.py tables; do not edit.",
        "",
        "/// Not `str.isprintable()`.",
    ]
    out += rust_table("NON_PRINTABLE", ranges(lambda c: not c.isprintable()))
    out += ["", "/// `str.isalnum()` (with `_`, what `re`'s `\\w` matches)."]
    out += rust_table("ALNUM", ranges(lambda c: c.isalnum()))
    path = ROOT / "native" / "kiwi-core" / "src" / "pystr_table.rs"
    path.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")


