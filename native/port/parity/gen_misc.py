EPOCH = datetime(1970, 1, 1)


def linux_fromtimestamp(unix: int, tz):
    utc = EPOCH + timedelta(seconds=unix)
    return tz.fromutc(utc.replace(tzinfo=tz))


def offset_secs(dt) -> int:
    o = dt.utcoffset()
    return o.days * 86400 + o.seconds


def zone_transitions(key: str) -> list[int]:
    from zoneinfo._zoneinfo import ZoneInfo as PyZoneInfo

    z = PyZoneInfo.no_cache(key)
    ts = [t for t in z._trans_utc if -30_000_000_000 < t < 4_102_444_800]
    from zoneinfo import ZoneInfo

    cz = ZoneInfo(key)
    for year in (2026, 2037, 2038, 2050, 2100, 2401, 3000, 5000, 9998):
        start = int(datetime(year, 1, 1, tzinfo=UTC).timestamp())
        prev = offset_secs(linux_fromtimestamp(start, cz))
        for day in range(1, 367):
            t = start + day * 86400
            cur = offset_secs(linux_fromtimestamp(t, cz))
            if cur != prev:
                lo, hi = t - 86400, t
                while hi - lo > 1:
                    mid = (lo + hi) // 2
                    if offset_secs(linux_fromtimestamp(mid, cz)) == prev:
                        lo = mid
                    else:
                        hi = mid
                ts.append(hi)
                prev = cur
    return sorted(set(ts))


